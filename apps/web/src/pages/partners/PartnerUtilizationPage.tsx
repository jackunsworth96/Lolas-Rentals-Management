import { useMemo, useState } from 'react';
import { Link } from 'react-router-dom';
import { usePartnerUtilization } from '../../api/partners.js';
import { formatCurrency } from '../../utils/currency.js';

type Period = '7d' | '30d' | '90d' | 'custom';

function manilaToday(): string {
  return new Date().toLocaleDateString('en-CA', { timeZone: 'Asia/Manila' });
}

function addDaysToDateStr(dateStr: string, days: number): string {
  const [y, m, d] = dateStr.split('-').map(Number);
  return new Date(Date.UTC(y, m - 1, d + days)).toISOString().slice(0, 10);
}

const PERIOD_DAYS: Record<Exclude<Period, 'custom'>, number> = { '7d': 7, '30d': 30, '90d': 90 };

export default function PartnerUtilizationPage() {
  const [period, setPeriod] = useState<Period>('30d');
  const [customFrom, setCustomFrom] = useState('');
  const [customTo, setCustomTo] = useState('');

  const today = manilaToday();
  const { from, to } = useMemo(() => {
    if (period === 'custom') return { from: customFrom, to: customTo };
    const days = PERIOD_DAYS[period];
    return { from: addDaysToDateStr(today, -days), to: today };
  }, [period, customFrom, customTo, today]);

  const { data, isLoading, error } = usePartnerUtilization(from, to);

  return (
    <div>
      <div className="mb-6 flex flex-wrap items-center justify-between gap-4">
        <div className="flex items-center gap-4">
          <h1 className="text-2xl font-bold text-gray-900">Partner utilization</h1>
          <Link to="/partners" className="text-sm text-blue-600 hover:underline">
            ← Back to partners
          </Link>
        </div>
        <div className="flex flex-wrap items-start gap-3">
          <div className="flex rounded-lg border border-gray-300 p-0.5">
            {(['7d', '30d', '90d', 'custom'] as const).map((p) => (
              <button
                key={p}
                type="button"
                onClick={() => setPeriod(p)}
                className={`rounded-md px-3 py-1.5 text-sm ${period === p ? 'bg-gray-200 font-medium' : 'text-gray-600'}`}
              >
                {p === 'custom' ? 'Custom' : p}
              </button>
            ))}
          </div>
          {period === 'custom' && (
            <>
              <input
                type="date"
                value={customFrom}
                onChange={(e) => setCustomFrom(e.target.value)}
                className="rounded-lg border border-gray-300 px-3 py-2 text-sm"
              />
              <span className="text-gray-500">to</span>
              <input
                type="date"
                value={customTo}
                onChange={(e) => setCustomTo(e.target.value)}
                className="rounded-lg border border-gray-300 px-3 py-2 text-sm"
              />
            </>
          )}
        </div>
      </div>

      <p className="mb-4 text-sm text-gray-500">
        Rental days &amp; revenue generated by each partner&apos;s referred bookings. For partners with a
        Protected allocation configured, quota usage shows how much of their guaranteed pool they actually used.
      </p>

      {period === 'custom' && (!customFrom || !customTo) ? (
        <div className="py-12 text-center text-sm text-gray-500">Choose a start and end date.</div>
      ) : isLoading ? (
        <div className="py-12 text-center text-gray-500">Loading partner utilization...</div>
      ) : error ? (
        <div className="py-12 text-center text-red-600">{(error as Error).message}</div>
      ) : !data ? null : (
        <>
          <p className="mb-4 text-sm text-gray-500">
            Period: {data.from} to {data.to}
          </p>
          <div className="overflow-x-auto rounded-lg border border-gray-200">
            <table className="min-w-full divide-y divide-gray-200">
              <thead className="bg-gray-50">
                <tr>
                  <th className="px-4 py-3 text-left text-xs font-medium uppercase tracking-wider text-gray-500">Partner</th>
                  <th className="px-4 py-3 text-right text-xs font-medium uppercase tracking-wider text-gray-500">Bookings</th>
                  <th className="px-4 py-3 text-right text-xs font-medium uppercase tracking-wider text-gray-500">Rental days</th>
                  <th className="px-4 py-3 text-right text-xs font-medium uppercase tracking-wider text-gray-500">Revenue</th>
                  <th className="px-4 py-3 text-left text-xs font-medium uppercase tracking-wider text-gray-500">Guaranteed quota usage</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-gray-200 bg-white">
                {data.partners.map((p) => (
                  <tr key={p.partnerId}>
                    <td className="whitespace-nowrap px-4 py-3 text-sm font-medium text-gray-900">{p.partnerName}</td>
                    <td className="whitespace-nowrap px-4 py-3 text-sm text-right text-gray-900">{p.bookingsCount}</td>
                    <td className="whitespace-nowrap px-4 py-3 text-sm text-right text-gray-900">{p.rentalDays}</td>
                    <td className="whitespace-nowrap px-4 py-3 text-sm text-right text-gray-900">{formatCurrency(p.revenue)}</td>
                    <td className="px-4 py-3 text-sm text-gray-600">
                      {p.quota.length === 0 ? (
                        <span className="text-gray-400">—</span>
                      ) : (
                        <div className="flex flex-col gap-0.5">
                          {p.quota.map((q) => (
                            <span key={q.vehicleType}>
                              {q.vehicleType}: {q.quotaUtilizationPercent === null ? 'No allocation' : `${q.quotaUtilizationPercent}%`}{' '}
                              <span className="text-gray-400">
                                ({q.guaranteedHours.toFixed(1)} / {q.allocatedHours.toFixed(1)} hrs)
                              </span>
                            </span>
                          ))}
                        </div>
                      )}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
          {data.partners.length === 0 && (
            <div className="py-8 text-center text-sm text-gray-500">No partners in scope for this period.</div>
          )}
        </>
      )}
    </div>
  );
}
