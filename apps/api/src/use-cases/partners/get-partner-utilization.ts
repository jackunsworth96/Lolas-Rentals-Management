import { getSupabaseClient } from '../../adapters/supabase/client.js';
import { manilaMidnightMs } from '../../utils/manila-date.js';
import { DAY_MS, computeOrderItemOverlap, attributeAddonRevenue, type AddonRow } from '../shared/rental-period-overlap.js';
import { allocationReport } from '../../lib/partner-allocation-report.js';

export interface PartnerQuotaRow {
  vehicleType: string;
  allocatedHours: number;
  guaranteedHours: number;
  overflowHours: number;
  /** Share of the partner's guaranteed quota actually used, as a percentage. Null if no quota was allocated in this period. */
  quotaUtilizationPercent: number | null;
}

export interface PartnerUtilizationRow {
  partnerId: string;
  partnerName: string;
  storeId: string;
  /** Distinct active/completed orders referred by this partner that overlapped the period. */
  bookingsCount: number;
  rentalDays: number;
  revenue: number;
  /** Guaranteed-allocation usage, present only for partners whose store has Protected allocations enabled and who have a configured quota. */
  quota: PartnerQuotaRow[];
}

export interface PartnerUtilizationResult {
  from: string;
  to: string;
  partners: PartnerUtilizationRow[];
}

type PartnerRow = { id: string; name: string; slug: string; store_id: string };

/**
 * Rental activity (days/revenue, same proration rules as fleet utilization)
 * generated by each partner's referred bookings in [from, to), plus — for
 * partners whose store has Protected allocations enabled — how much of their
 * guaranteed vehicle quota they actually used (reusing the existing
 * allocationReport engine that already powers the per-partner allocation page).
 */
export async function getPartnerUtilization(
  from: string,
  to: string,
  storeIds?: string[],
): Promise<PartnerUtilizationResult> {
  const sb = getSupabaseClient();
  const periodStartMs = manilaMidnightMs(from);
  const periodEndMs = manilaMidnightMs(to);

  let partnerQuery = sb.from('accommodation_partners').select('id, name, slug, store_id').eq('status', 'active');
  if (storeIds && storeIds.length > 0) partnerQuery = partnerQuery.in('store_id', storeIds);
  const { data: partnerRows, error: partnerErr } = await partnerQuery;
  if (partnerErr) throw new Error(`Partners query failed: ${partnerErr.message}`);
  const partners = (partnerRows ?? []) as PartnerRow[];
  if (partners.length === 0) return { from, to, partners: [] };

  const slugs = partners.map((p) => p.slug);

  // Orders referred by these partners — any status filter happens below via
  // 'active'/'completed', matching the same revenue-recognition rule as fleet utilization.
  const orderIdToPartnerSlug = new Map<string, string>();
  for (let i = 0; i < slugs.length; i += 100) {
    const { data: orderRows, error: orderErr } = await sb
      .from('orders')
      .select('id, partner_ref')
      .in('partner_ref', slugs.slice(i, i + 100))
      .in('status', ['active', 'completed']);
    if (orderErr) throw new Error(`Orders query failed: ${orderErr.message}`);
    for (const o of (orderRows ?? []) as Array<{ id: string; partner_ref: string | null }>) {
      if (o.partner_ref) orderIdToPartnerSlug.set(o.id, o.partner_ref);
    }
  }

  const orderIds = [...orderIdToPartnerSlug.keys()];

  interface OrderItemRow {
    id: string;
    order_id: string;
    rental_days_count: number;
    rental_rate: number;
    pickup_fee: number;
    dropoff_fee: number;
    discount: number;
    pickup_datetime: string | null;
    dropoff_datetime: string | null;
  }

  let orderItems: OrderItemRow[] = [];
  if (orderIds.length > 0) {
    const queryFloor = new Date(periodStartMs - DAY_MS).toISOString();
    const queryCeiling = new Date(periodEndMs + DAY_MS).toISOString();
    for (let i = 0; i < orderIds.length; i += 100) {
      const { data, error } = await sb
        .from('order_items')
        .select('id, order_id, rental_days_count, rental_rate, pickup_fee, dropoff_fee, discount, pickup_datetime, dropoff_datetime')
        .in('order_id', orderIds.slice(i, i + 100))
        .lte('pickup_datetime', queryCeiling)
        .gte('dropoff_datetime', queryFloor);
      if (error) throw new Error(`Order items query failed: ${error.message}`);
      orderItems = orderItems.concat((data ?? []) as OrderItemRow[]);
    }
  }

  interface Agg { rentalDays: number; revenue: number; orderIds: Set<string> }
  const aggBySlug: Record<string, Agg> = {};
  const contributingItemsByOrder: Record<string, Array<{ slug: string; overlapDays: number; totalBookingDays: number }>> = {};

  for (const item of orderItems) {
    const slug = orderIdToPartnerSlug.get(item.order_id);
    if (!slug) continue;
    const overlap = computeOrderItemOverlap(item, periodStartMs, periodEndMs);
    if (!overlap) continue;

    const agg = (aggBySlug[slug] ??= { rentalDays: 0, revenue: 0, orderIds: new Set() });
    agg.rentalDays += overlap.overlapDays;
    agg.revenue += overlap.revenue;
    agg.orderIds.add(item.order_id);

    (contributingItemsByOrder[item.order_id] ??= []).push({
      slug,
      overlapDays: overlap.overlapDays,
      totalBookingDays: overlap.totalBookingDays,
    });
  }

  if (orderIds.length > 0) {
    let addonRows: AddonRow[] = [];
    for (let i = 0; i < orderIds.length; i += 100) {
      const { data, error } = await sb
        .from('order_addons')
        .select('order_id, addon_type, total_amount, added_at')
        .in('order_id', orderIds.slice(i, i + 100));
      if (error) throw new Error(`Order addons query failed: ${error.message}`);
      addonRows = addonRows.concat((data ?? []) as AddonRow[]);
    }
    attributeAddonRevenue(addonRows, contributingItemsByOrder, periodStartMs, periodEndMs, (item, amount) => {
      aggBySlug[item.slug].revenue += amount;
    });
  }

  // Guaranteed-allocation ("Protected allocations") usage, only for stores that have it enabled.
  const quotaByPartnerId = await getPartnerQuotaUsage(sb, partners, from, to);

  const resultRows: PartnerUtilizationRow[] = partners
    .map((p) => {
      const agg = aggBySlug[p.slug] ?? { rentalDays: 0, revenue: 0, orderIds: new Set<string>() };
      return {
        partnerId: p.id,
        partnerName: p.name,
        storeId: p.store_id,
        bookingsCount: agg.orderIds.size,
        rentalDays: agg.rentalDays,
        revenue: Math.round(agg.revenue * 100) / 100,
        quota: quotaByPartnerId[p.id] ?? [],
      };
    })
    .sort((a, b) => b.revenue - a.revenue);

  return { from, to, partners: resultRows };
}

type SupabaseClientLike = ReturnType<typeof getSupabaseClient>;

async function getPartnerQuotaUsage(
  sb: SupabaseClientLike,
  partners: PartnerRow[],
  from: string,
  to: string,
): Promise<Record<string, PartnerQuotaRow[]>> {
  const storeIdsWithPartners = [...new Set(partners.map((p) => p.store_id))];
  if (storeIdsWithPartners.length === 0) return {};

  const { data: settingsRows, error: settingsErr } = await sb
    .from('partner_allocation_settings')
    .select('store_id, enabled')
    .in('store_id', storeIdsWithPartners);
  if (settingsErr) throw new Error(`Partner allocation settings query failed: ${settingsErr.message}`);
  const enabledStores = new Set(
    ((settingsRows ?? []) as Array<{ store_id: string; enabled: boolean }>)
      .filter((s) => s.enabled)
      .map((s) => s.store_id),
  );
  const quotaPartners = partners.filter((p) => enabledStores.has(p.store_id));
  if (quotaPartners.length === 0) return {};

  const partnerIds = quotaPartners.map((p) => p.id);
  const [baselineResult, overrideResult] = await Promise.all([
    sb.from('partner_allocations').select('partner_id, vehicle_type, effective_month, scheduled_qty').in('partner_id', partnerIds),
    sb.from('partner_allocation_overrides').select('partner_id, vehicle_type, starts_on, ends_before, qty').in('partner_id', partnerIds).is('revoked_at', null),
  ]);
  if (baselineResult.error) throw new Error(`Partner allocations query failed: ${baselineResult.error.message}`);
  if (overrideResult.error) throw new Error(`Partner allocation overrides query failed: ${overrideResult.error.message}`);

  type Baseline = { partner_id: string; vehicle_type: string; effective_month: string; scheduled_qty: number };
  type Override = { partner_id: string; vehicle_type: string; starts_on: string; ends_before: string; qty: number };
  const baselines = (baselineResult.data ?? []) as Baseline[];
  const overrides = (overrideResult.data ?? []) as Override[];

  const typesByPartner = new Map<string, Set<string>>();
  for (const b of baselines) (typesByPartner.get(b.partner_id) ?? typesByPartner.set(b.partner_id, new Set()).get(b.partner_id)!).add(b.vehicle_type);
  for (const o of overrides) (typesByPartner.get(o.partner_id) ?? typesByPartner.set(o.partner_id, new Set()).get(o.partner_id)!).add(o.vehicle_type);

  const now = Date.now();
  const quotaByPartnerId: Record<string, PartnerQuotaRow[]> = {};

  for (const partner of quotaPartners) {
    const types = typesByPartner.get(partner.id);
    if (!types || types.size === 0) continue;
    const rows: PartnerQuotaRow[] = [];
    for (const vehicleType of types) {
      const { data: reservations, error: resErr } = await sb
        .from('capacity_reservations')
        .select('id,actual_start,actual_end,ends_at,capacity_reservation_segments(reservation_id,starts_at,ends_at,pool)')
        .eq('partner_id', partner.id)
        .eq('vehicle_type', vehicleType)
        .not('actual_start', 'is', null)
        .lt('starts_at', `${to}T00:00:00+08:00`)
        .gt('ends_at', `${from}T00:00:00+08:00`);
      if (resErr) throw new Error(`Capacity reservations query failed: ${resErr.message}`);

      type ReservationRow = {
        id: string;
        actual_start: string | null;
        actual_end: string | null;
        ends_at: string;
        capacity_reservation_segments: Array<{ reservation_id: string; starts_at: string; ends_at: string; pool: string }>;
      };
      const reservationRows = (reservations ?? []) as ReservationRow[];
      const segments = reservationRows.flatMap((r) => r.capacity_reservation_segments ?? []);

      const report = allocationReport({
        from,
        to,
        now,
        baselines: baselines.filter((b) => b.partner_id === partner.id && b.vehicle_type === vehicleType),
        overrides: overrides.filter((o) => o.partner_id === partner.id && o.vehicle_type === vehicleType),
        reservations: reservationRows,
        segments,
      });
      const totals = report.months.reduce(
        (acc, m) => ({
          allocatedHours: acc.allocatedHours + m.allocatedHours,
          guaranteedHours: acc.guaranteedHours + m.guaranteedHours,
          overflowHours: acc.overflowHours + m.overflowHours,
        }),
        { allocatedHours: 0, guaranteedHours: 0, overflowHours: 0 },
      );
      rows.push({
        vehicleType,
        allocatedHours: Math.round(totals.allocatedHours * 10) / 10,
        guaranteedHours: Math.round(totals.guaranteedHours * 10) / 10,
        overflowHours: Math.round(totals.overflowHours * 10) / 10,
        quotaUtilizationPercent: totals.allocatedHours > 0
          ? Math.round((totals.guaranteedHours / totals.allocatedHours) * 1000) / 10
          : null,
      });
    }
    if (rows.length > 0) quotaByPartnerId[partner.id] = rows;
  }

  return quotaByPartnerId;
}
